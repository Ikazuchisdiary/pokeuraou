//! An ability or item the engine never names is one its gates may take without code of
//! their own: whatever Showdown does with it, the port does nothing, and `modelled.rs` says
//! whether that nothing needs a note. Deciding which ids those are by memory is how a port
//! acquires a silent wrong answer, so it is decided by scanning the engine's source:
//! `tools/port_coverage.py --rust` regenerates this file, and it must be regenerated when
//! the engine learns a new effect (IKA-210; it was Python's source until then).

